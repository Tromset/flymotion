#!/usr/bin/env python3
"""Writes the Modelfiles from the Microduck profile and the system prompt, so the published models and the bridge
always agree. `python3 scripts/gen_modelfiles.py --check` fails when a Modelfile is out of date (run by the tests)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from flymotion.plan import load_profile  # noqa: E402
from flymotion.prompt import system_prompt  # noqa: E402

VERSION = '0.2'
# file, published name, Ollama base, base description, what it runs on
VARIANTS = [
    ('Modelfile', f'flymotion{VERSION}', 'qwen3.5:4b', 'Qwen3.5 4B', 'any computer with 8 GB of memory'),
    ('Modelfile.lite', f'flymotion{VERSION}lite', 'qwen3.5:2b', 'Qwen3.5 2B', 'a Raspberry Pi 5 or any computer with 4 GB of memory'),
]


def render(name, base, description, runs_on):
    prompt = system_prompt(load_profile('microduck'))
    return f'''# FlyMotion {VERSION}: plans the motion of a small robot (Microduck) from natural language. Runs on {runs_on}.
# Base: {description} (Apache 2.0). Published as Tromset/{name}. Build: ollama create {name} -f <this file>
# Generated by scripts/gen_modelfiles.py from robots/microduck.json and flymotion/prompt.py: edit those, not this file.
# Use it through the bridge (python -m flymotion), which sends the JSON schema and turns thinking off.
FROM {base}
REQUIRES 0.30.0

# A plan is short: a small context keeps memory low and the first token fast.
PARAMETER num_ctx 2048
PARAMETER num_predict 384
# Qwen3.5 is a hybrid model: Ollama can only reuse the cached system prompt up to one batch before the end of the
# last prompt. Small batches keep almost all of it: on a 4-core CPU the 2B reads the request in 1 s instead of 11 s.
PARAMETER num_batch 32

# Low temperature: the same request gives the same motion.
PARAMETER temperature 0.2
PARAMETER top_k 20
PARAMETER top_p 0.8
PARAMETER repeat_penalty 1

SYSTEM """{prompt}"""
'''


def main():
    check = '--check' in sys.argv
    stale = []
    for file, name, base, description, runs_on in VARIANTS:
        text = render(name, base, description, runs_on)
        path = ROOT / file
        if check:
            if not path.is_file() or path.read_text() != text:
                stale.append(file)
        else:
            path.write_text(text)
            print(f'wrote {file} ({name}, {base})')
    if stale:
        sys.exit(f'Out of date: {", ".join(stale)}. Run: python3 scripts/gen_modelfiles.py')


if __name__ == '__main__':
    main()
